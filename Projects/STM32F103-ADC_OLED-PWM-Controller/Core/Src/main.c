void Process_ADC_Data(uint16_t *data, uint16_t size)
{
    uint32_t sum = 0;

    for(int i = 0; i < size; i++)
    {
        sum += data[i];
    }

    uint32_t average = sum / size;

    voltage = (average * 3.3f) / 4095.0f;

    pwm_value = (average * 999) / 4095;

    __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, pwm_value);

    pwm_percent = (pwm_value / 999.0f) * 100.0f;
}

